def quadrado(x):
    return x * x

resultado = quadrado(float(input("Digite um número para calcular o quadrado: "))) # essa linha de código chama a função quadrado() e passa o argumento x para o parâmetro x.
print(f"O quadrado do número é: {resultado}") # o return da função quadrado() é armazenado na variável resultado e depois impresso na tela.